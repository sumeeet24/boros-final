export async function getAllProducts() {
    return mockProducts;
}

export async function getProductBySlug(slug) {
    return mockProducts.find(p => p.fields.slug === slug);
}

export async function getProductsByCategory(categoryType) {
    if (!categoryType || categoryType === "all") return mockProducts;
    return mockProducts.filter(p => p.fields.categoryType === categoryType);
}

export async function getProductsByBrand(brand) {
    if (!brand) return mockProducts;
    return mockProducts.filter(p => p.fields.brand.toLowerCase().includes(brand.toLowerCase()));
}